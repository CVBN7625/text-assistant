import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = dirname(require.resolve('lxgw-wenkai-screen-webfont/package.json'));
const sourceCssPath = join(packageRoot, 'lxgwwenkaigbscreen.css');
const outputRoot = join(root, 'packages/web/public/fonts/lxgw-wenkai-screen');
const outputFilesRoot = join(outputRoot, 'files');
const checkOnly = process.argv.includes('--check');
const sourceRoots = [
  join(root, 'packages/web/src'),
  join(root, 'packages/core/src')
];
const sourceExtensions = new Set(['.ts', '.vue', '.css']);
const familyName = 'LXGW WenKai Screen';
const metadataFileCount = 4;

function walkFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walkFiles(path) : [path];
  });
}

function collectCodePoints() {
  const codePoints = new Set();

  for (const sourceRoot of sourceRoots) {
    for (const path of walkFiles(sourceRoot)) {
      if (!sourceExtensions.has(extname(path))) continue;
      for (const character of readFileSync(path, 'utf8')) {
        codePoints.add(character.codePointAt(0));
      }
    }
  }

  return codePoints;
}

function parseRange(value) {
  return value.split(',').map(item => {
    const [start, end = start] = item.trim().replace(/^U\+/i, '').split('-');
    return [Number.parseInt(start, 16), Number.parseInt(end, 16)];
  });
}

function matchesCodePoints(ranges, codePoints) {
  for (const codePoint of codePoints) {
    if (ranges.some(([start, end]) => codePoint >= start && codePoint <= end)) return true;
  }
  return false;
}

function buildExpectedFiles() {
  const codePoints = collectCodePoints();
  const sourceCss = readFileSync(sourceCssPath, 'utf8');
  const blocks = [...sourceCss.matchAll(/\/\*[\s\S]*?\*\/\s*@font-face\s*\{[\s\S]*?\}/g)];
  const selected = blocks
    .map(match => match[0])
    .filter(block => {
      const range = block.match(/unicode-range:\s*([^;}\n]+)/)?.[1];
      return range && matchesCodePoints(parseRange(range), codePoints);
    });

  const expected = new Map();
  const rewrittenCss = selected
    .map(block =>
      block.replace(
        /url\('\.\/files\/([^']+)'\)/,
        (_, file) => `url('/fonts/lxgw-wenkai-screen/files/${file}')`
      )
    )
    .join('\n\n');

  expected.set('font.css', `${rewrittenCss}\n`);
  expected.set('OFL.txt', readFileSync(join(packageRoot, 'OFL.txt')));
  expected.set('PACKAGE-LICENSE.txt', readFileSync(join(packageRoot, 'LICENSE')));
  expected.set(
    'SOURCE.md',
    `# LXGW WenKai Screen Web Font\n\n` +
      `- Package: \`lxgw-wenkai-screen-webfont@1.7.0\`\n` +
      `- Font family: \`${familyName}\`\n` +
      `- Font license: SIL Open Font License 1.1; see \`OFL.txt\`.\n` +
      `- Webfont package license: MIT; see \`PACKAGE-LICENSE.txt\`.\n` +
      `- Generated by: \`corepack pnpm font:generate\`\n` +
      `- Included subsets: ${selected.length}\n`
  );

  for (const block of selected) {
    const file = block.match(/url\('\.\/files\/([^']+)'\)/)?.[1];
    if (file) expected.set(join('files', file), readFileSync(join(packageRoot, 'files', file)));
  }

  return expected;
}

function existingOutputFiles() {
  if (!existsSync(outputRoot)) return [];
  return walkFiles(outputRoot).map(path => relative(outputRoot, path));
}

function check(expected) {
  const expectedNames = [...expected.keys()].sort();
  const existingNames = existingOutputFiles().sort();
  const namesMatch = JSON.stringify(expectedNames) === JSON.stringify(existingNames);
  const contentsMatch =
    namesMatch &&
    expectedNames.every(name => {
      const expectedContent = expected.get(name);
      const actualContent = readFileSync(join(outputRoot, name));
      return Buffer.from(expectedContent).equals(actualContent);
    });

  if (!contentsMatch) {
    console.error('Sunflower Web font assets are stale. Run: corepack pnpm font:generate');
    process.exitCode = 1;
    return;
  }

  console.log(`Sunflower Web font assets are current (${expectedNames.length - metadataFileCount} WOFF2 subsets).`);
}

function generate(expected) {
  rmSync(outputRoot, { recursive: true, force: true });
  mkdirSync(outputFilesRoot, { recursive: true });

  for (const [name, content] of expected) {
    const destination = join(outputRoot, name);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, content);
  }

  const bytes = existingOutputFiles().reduce((total, name) => total + readFileSync(join(outputRoot, name)).byteLength, 0);
  console.log(`Generated ${expected.size - metadataFileCount} WOFF2 subsets (${(bytes / 1024 / 1024).toFixed(2)} MB).`);
}

const expected = buildExpectedFiles();
if (checkOnly) check(expected);
else generate(expected);
